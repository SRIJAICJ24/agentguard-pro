def write_starter_policy(directory: Path | None = None, *,
                         enforcement: bool = False) -> Path | None:
    """Create `agentguard.policy.yaml` unless one already exists.

    Never overwrites: an existing policy is the user's security configuration and
    the wizard has no business replacing it.
    """
    target = (directory or Path.cwd()) / "agentguard.policy.yaml"
    if target.exists():
        return None
    target.write_text(
        STARTER_POLICY.format(enforcement="true" if enforcement else "false"),
        encoding="utf-8",
    )
    return target


# --- daemon installation ---------------------------------------------------
@dataclass
class DaemonPlan:
    """What installing the daemon would write, and how to turn it on."""

    platform: str
    path: Path
    content: str
    activate_cmd: list[str]
    deactivate_hint: str = ""
    # Additional files the definition needs (Windows: a hidden-window launcher).
    extra_files: dict[Path, str] | None = None
    # Run after activate_cmd to start the service now rather than at next login.
    start_cmd: list[str] | None = None

    @property
    def activate_display(self) -> str:
        """The activation command as the user would type it, quoted where needed."""
        return " ".join(_quote(part) for part in self.activate_cmd)


def _console_parts() -> list[str]:
    """The command to launch AgentGuard, as separate argv parts.

    A list rather than a string because an interpreter path can contain spaces
    ("C:\\Program Files\\..."), and splitting a joined string back apart would
    corrupt it. Callers that need a single line quote the parts themselves.
    """
    found = shutil.which("agentguard")
    return [found] if found else [sys.executable, "-m", "agentguard.cli"]


def _quote(part: str) -> str:
    """Quote one argv part for a shell-style command line."""
    return f'"{part}"' if (" " in part and not part.startswith('"')) else part


def _command_line(parts: list[str]) -> str:
    return " ".join(_quote(p) for p in parts)


def _gateway_args(config: Config) -> list[str]:
    args = ["proxy", "--port", str(config.port)]
    if config.upstream:
        args += ["--upstream", config.upstream]
    if config.enforcement:
        args.append("--enforce")
    return args


def build_daemon_plan(config: Config, *, system: str | None = None,
                      home: Path | None = None) -> DaemonPlan:
    """Produce the service definition for this OS without writing anything."""
    system = (system or platform.system()).lower()
    base = home or Path.home()
    argv = [*_console_parts(), *_gateway_args(config)]
    command = _command_line(argv)

    if system == "linux":
        path = base / ".config" / "systemd" / "user" / f"{SERVICE_NAME}.service"
        content = f"""[Unit]
Description=AgentGuard - runtime security gateway for MCP agents
After=network.target

[Service]
Type=simple
ExecStart={command}
Restart=on-failure
RestartSec=5
Environment=AGENTGUARD_HOME={cfg.agentguard_home()}

[Install]
WantedBy=default.target
"""
        return DaemonPlan(
            "linux", path, content,
            ["systemctl", "--user", "enable", "--now", SERVICE_NAME],
            f"systemctl --user disable --now {SERVICE_NAME}",
        )

    if system == "darwin":
        path = base / "Library" / "LaunchAgents" / f"{LAUNCHD_LABEL}.plist"
        from xml.sax.saxutils import escape

        # launchd takes argv as separate array elements, so no quoting is needed -
        # only XML escaping, since a path may legitimately contain & or <.
        arg_xml = "\n".join(f"    <string>{escape(part)}</string>" for part in argv)
        content = f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>{LAUNCHD_LABEL}</string>
  <key>ProgramArguments</key>
  <array>
{arg_xml}
  </array>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>EnvironmentVariables</key>
  <dict>
    <key>AGENTGUARD_HOME</key>
    <string>{cfg.agentguard_home()}</string>
  </dict>
</dict>
</plist>
"""
        return DaemonPlan(
            "darwin", path, content,
            ["launchctl", "load", "-w", str(path)],
            f"launchctl unload -w {path}",
        )

    if system == "windows":
        # Task Scheduler cannot take a multi-part command directly, so the task
        # runs a small launcher script that Task Scheduler can point at as one file.
        #
        # The .cmd restarts the daemon if it exits (Task Scheduler has no
        # restart-on-crash for logon tasks), logs to daemon.log, and stops for good
        # when `agentguard daemon stop` leaves a daemon.stop flag. A .vbs wrapper
        # starts it with no console window, so there's no window to close by
        # accident - closing a terminal no longer stops AgentGuard.
        home_dir = cfg.agentguard_home()
        path = home_dir / "agentguard-daemon.cmd"
        launcher = home_dir / "agentguard-daemon.vbs"
        content = (
            "@echo off\r\n"
            "rem Launcher for the AgentGuard daemon, run by Task Scheduler.\r\n"
            f"set AGENTGUARD_HOME={home_dir}\r\n"
            'if exist "%AGENTGUARD_HOME%\\daemon.stop" del "%AGENTGUARD_HOME%\\daemon.stop"\r\n'
            ":loop\r\n"
            f'{command} >> "%AGENTGUARD_HOME%\\daemon.log" 2>&1\r\n'
            'if exist "%AGENTGUARD_HOME%\\daemon.stop" goto end\r\n'
            "timeout /t 5 /nobreak >nul\r\n"
            "goto loop\r\n"
            ":end\r\n"
        )
        vbs = (
            "' Starts agentguard-daemon.cmd with no console window.\r\n"
            'CreateObject("WScript.Shell").Run """' + str(path) + '""", 0, False\r\n'
        )
        return DaemonPlan(
            "windows", path, content,
            ["schtasks", "/Create", "/TN", WINDOWS_TASK_NAME,
             "/TR", f'wscript.exe "{launcher}"', "/SC", "ONLOGON", "/F"],
            f"agentguard daemon stop && schtasks /Delete /TN {WINDOWS_TASK_NAME} /F",
            extra_files={launcher: vbs},
            start_cmd=["schtasks", "/Run", "/TN", WINDOWS_TASK_NAME],
        )

    raise RuntimeError(
        f"unsupported platform {system!r} - install a service manually using "
        f"`{command}`"
    )


def install_daemon(config: Config, *, system: str | None = None,
                   home: Path | None = None, activate: bool = False) -> DaemonPlan:
    """Write the service definition. Only activates when explicitly asked."""
    plan = build_daemon_plan(config, system=system, home=home)
    plan.path.parent.mkdir(parents=True, exist_ok=True)
    plan.path.write_text(plan.content, encoding="utf-8")
    if plan.platform == "windows":
        os.chmod(plan.path, 0o755)
    for extra_path, extra_content in (plan.extra_files or {}).items():
        extra_path.parent.mkdir(parents=True, exist_ok=True)
        extra_path.write_text(extra_content, encoding="utf-8")

    if activate:
        for step in (plan.activate_cmd, plan.start_cmd):
            if not step:
                continue
            try:
                subprocess.run(step, check=True, capture_output=True, text=True)
            except (subprocess.CalledProcessError, FileNotFoundError) as exc:
                detail = getattr(exc, "stderr", "") or str(exc)
                print(f"  could not run {' '.join(step[:3])}...: {detail.strip()[:200]}")
                print(f"  run this yourself: {' '.join(_quote(p) for p in step)}")
                break
    return plan


# --- the wizards -----------------------------------------------------------
def onboard(*, input_fn: InputFn = input, non_interactive: bool = False,
            install_daemon_flag: bool = False, activate: bool = False,
            policy_dir: Path | None = None,
            system: str | None = None, home: Path | None = None) -> Config:
    """Interactive first-run setup. Returns the saved config."""
    existing = None
    if cfg.exists():
        try:
            existing = cfg.load()
        except cfg.ConfigError:
            existing = None       # malformed: fall through to defaults and rewrite
    base = existing or Config()

    print("AgentGuard setup")
    print("  Answers in parentheses are defaults - press Enter to accept.\n")

    if non_interactive:
        config = base
    else:
        mode = ask(
            "Start in observe-only mode, or enforce (block) straight away?",
            base.mode, input_fn=input_fn, choices=(MODE_OBSERVE, MODE_ENFORCE),
        )
        port = ask_port("Port for the local gateway", base.port, input_fn=input_fn)
        dashboard = ask_bool("Enable the local dashboard?", base.dashboard,
                             input_fn=input_fn)
        dashboard_port = base.dashboard_port
        if dashboard:
            default_dash = base.dashboard_port if base.dashboard_port != port else port + 1
            dashboard_port = ask_port("Port for the dashboard", default_dash,
                                      input_fn=input_fn)
        config = Config(
            mode=mode, port=port, dashboard=dashboard, dashboard_port=dashboard_port,
            upstream=base.upstream, agent=base.agent, role=base.role,
            policy_file=base.policy_file, created_at=base.created_at,
        )

    problems = config.validate()
    if problems:
        # Most likely cause is the two ports colliding; fix rather than fail.
        if config.dashboard and config.port == config.dashboard_port:
            config.dashboard_port = config.port + 1
            print(f"  dashboard port collided with the gateway port; "
                  f"moved it to {config.dashboard_port}")
        problems = config.validate()
        if problems:
            raise cfg.ConfigError("; ".join(problems))

    path = cfg.save(config)
    print(f"\n  wrote {path}")

    policy = write_starter_policy(policy_dir, enforcement=config.enforcement)
    if policy:
        print(f"  wrote {policy}")
    else:
        print("  kept the existing agentguard.policy.yaml (not overwritten)")

    if install_daemon_flag:
        try:
            plan = install_daemon(config, system=system, home=home, activate=activate)
        except RuntimeError as exc:
            print(f"  daemon: {exc}")
        else:
            print(f"  wrote {plan.path}  ({plan.platform} service definition)")
            if not activate:
                print(f"\n  to start it on login, run:\n    {plan.activate_display}")
                print(f"  to undo:\n    {plan.deactivate_hint}")

    mode_note = "ENFORCING - calls will be blocked" if config.enforcement else \
        "observe only - nothing will be blocked yet"
    print(f"\n  mode: {mode_note}")
    print("\nNext steps:")
    print("  1. agentguard install-hooks          # see Claude Code's own tools")
    print("  2. agentguard doctor")
    if config.upstream:
        print(f"  3. claude mcp add --transport http agentguard "
              f"http://localhost:{config.port}/mcp")
    print("  -  agentguard audit --last 20      # see what it would have done")
    return config


SETTING_CHOICES = ("port", "mode", "dashboard", "dashboard_port", "upstream",
                   "hook_fail_mode", "hook_timeout")


def configure(setting: str | None = None, value: str | None = None, *,
              input_fn: InputFn = input) -> Config:
    """Change one setting without redoing onboarding."""
    try:
        config = cfg.load()
    except cfg.ConfigError as exc:
        raise cfg.ConfigError(
            f"{exc}\nrun `agentguard onboard` to rewrite the config"
        ) from exc

    if setting is None:
        print("Current settings:")
        for name in SETTING_CHOICES:
            print(f"  {name:16s} {getattr(config, name)}")
        print()
        setting = ask("Which setting?", "mode", input_fn=input_fn,
                      choices=SETTING_CHOICES)

    if setting not in SETTING_CHOICES:
        raise cfg.ConfigError(
            f"unknown setting {setting!r}; choose one of {', '.join(SETTING_CHOICES)}"
        )

    if setting == "mode":
        config.mode = value.lower() if value else ask(
            "Mode", config.mode, input_fn=input_fn, choices=(MODE_OBSERVE, MODE_ENFORCE)
        )
    elif setting == "dashboard":
        if value is not None:
            config.dashboard = value.lower() in ("y", "yes", "true", "1", "on")
        else:
            config.dashboard = ask_bool("Enable the dashboard?", config.dashboard,
                                        input_fn=input_fn)
    elif setting == "upstream":
        config.upstream = value if value is not None else ask(
            "Upstream MCP server", config.upstream or "", input_fn=input_fn
        ) or None
    elif setting == "hook_fail_mode":
        config.hook_fail_mode = (value or ask(
            "When the daemon is unreachable, Claude Code's command hook should fail",
            config.hook_fail_mode, input_fn=input_fn, choices=("open", "closed"),
        )).lower()
    elif setting == "hook_timeout":
        raw = value if value is not None else ask(
            "Command-hook timeout in seconds", str(config.hook_timeout), input_fn=input_fn)
        try:
            config.hook_timeout = float(raw)
        except ValueError as exc:
            raise cfg.ConfigError(f"hook_timeout must be a number, got {raw!r}") from exc
    else:   # port / dashboard_port
        if value is not None:
            try:
                setattr(config, setting, int(value))
            except ValueError as exc:
                raise cfg.ConfigError(f"{setting} must be a number, got {value!r}") from exc
        else:
            setattr(config, setting,
                    ask_port(setting.replace("_", " "), getattr(config, setting),
                             input_fn=input_fn))

    problems = config.validate()
    if problems:
        raise cfg.ConfigError("; ".join(problems))

    path = cfg.save(config)
    print(f"  {setting} -> {getattr(config, setting)}")
    print(f"  wrote {path}")
    if setting == "mode":
        print("\n  note: this is the installation default. Precedence is "
              "`--enforce`/`--observe` on the command line, then this setting, "
              "then `enforcement:` in agentguard.policy.yaml. The gateway prints "
              "which one it used at startup.")
    return config
